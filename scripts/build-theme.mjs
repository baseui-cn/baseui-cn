import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const theme = JSON.parse(fs.readFileSync(path.join(root, "scripts/theme-definition.json"), "utf8"))
const presets = theme.presets
const defaultColor = presets.colors[presets.defaultColor]
const defaultRadius = presets.radii[presets.defaultRadius].value
const identityKeys = [
  "--primary",
  "--primary-foreground",
  "--accent",
  "--accent-foreground",
  "--ring",
]
for (const [id, preset] of Object.entries(presets.colors)) {
  for (const mode of ["light", "dark"]) {
    if (Object.keys(preset[mode]).sort().join() !== [...identityKeys].sort().join())
      throw new Error(`Invalid identity variables for ${id}/${mode}`)
  }
}
// Validate every alias graph before distributing it. External runtime styling
// is unnecessary: all public variable references resolve within this schema.
for (const mode of ["light", "dark"])
  for (const preset of Object.values(presets.colors)) {
    const vars = { "--radius": defaultRadius, ...theme.shared, ...theme[mode], ...preset[mode] }
    const visit = (name, chain = []) => {
      if (!(name in vars)) throw new Error(`Undefined theme alias: ${name}`)
      if (chain.includes(name))
        throw new Error(`Circular theme alias: ${[...chain, name].join(" -> ")}`)
      for (const [, next] of vars[name].matchAll(/var\((--[\w-]+)/g)) visit(next, [...chain, name])
    }
    for (const name of Object.keys(vars)) visit(name)
  }
const block = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n")}\n}`
const strategy = "@custom-variant dark (&:where(.dark, .dark *));"
// Only Phase 1's loading indicator consumes keyframes. Later popup families own
// lifecycle transitions; duration/easing roles are available without phantom utilities.
const foundation = `/* baseui-cn foundation */
@layer base {
  :root { color-scheme: light; }
  .dark { color-scheme: dark; }
}
@keyframes loading-spin { to { transform: rotate(360deg); } }
@utility loading-spinner { animation: loading-spin 1s linear infinite; }
@media (prefers-reduced-motion: reduce) {
  .loading-spinner { animation: none; }
}
`
const rootVars = {
  "--radius": defaultRadius,
  ...theme.shared,
  ...theme.light,
  ...defaultColor.light,
}
const darkVars = {
  ...Object.fromEntries(Object.entries(theme.shared).filter(([, value]) => /^var\(--/.test(value))),
  ...theme.dark,
  ...defaultColor.dark,
}
const consumerCSS = [
  strategy,
  block("@theme inline", theme.mappings),
  block(":root", rootVars),
  block(".dark", darkVars),
  foundation,
].join("\n\n")
// Docs retain their 14px unit bridge; radii follow the same public variable as
// consumers. Circular controls and deliberate picker geometry stay family-owned.
const docsRoot = { ...rootVars }
docsRoot["--component-unit"] = "calc(1rem / 14)"
docsRoot["--control-radius"] = "var(--radius)"
const previewCSS = [
  ...Object.entries(presets.colors).flatMap(([id, preset]) => [
    block(`body[data-home-color="${id}"]`, preset.light),
    block(`.dark body[data-home-color="${id}"]`, preset.dark),
  ]),
  ...Object.entries(presets.radii).map(([id, preset]) =>
    block(`body[data-home-radius="${id}"]`, {
      "--radius": preset.value,
      "--control-radius": "var(--radius)",
    })
  ),
].join("\n\n")
const outputs = {
  "apps/www/styles/theme.generated.css": `/* Generated by scripts/build-theme.mjs; do not edit. */\n${strategy}\n\n${block(":root", docsRoot)}\n\n${block(".dark", darkVars)}\n\n${previewCSS}\n\n${foundation}`,
  "packages/cli/src/utils/theme.generated.ts": `// Generated by scripts/build-theme.mjs; do not edit.\nexport const themeSchemaVersion = ${theme.schemaVersion}\nexport const themePresets = ${JSON.stringify(presets, null, 2)} as const\nexport const themeInline: Record<string, string> = ${JSON.stringify(theme.mappings, null, 2)}\nexport const themeRoot: Record<string, string> = ${JSON.stringify(rootVars, null, 2)}\nexport const themeDark: Record<string, string> = ${JSON.stringify(darkVars, null, 2)}\nexport const themeStrategy = ${JSON.stringify(strategy)}\nexport const themeFoundation = ${JSON.stringify(foundation)}\n`,
  "apps/www/lib/__generated__/theme.json":
    JSON.stringify(
      {
        schemaVersion: theme.schemaVersion,
        css: consumerCSS,
        presets,
        light: rootVars,
        dark: darkVars,
      },
      null,
      2
    ) + "\n",
}
for (const [file, content] of Object.entries(outputs)) {
  const target = path.join(root, file)
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content)
      throw new Error(`Theme output differs: ${file}`)
  } else fs.writeFileSync(target, content)
}
console.log(
  `Theme v${theme.schemaVersion}: ${Object.keys(outputs).length} outputs ${process.argv.includes("--check") ? "verified" : "generated"}`
)
